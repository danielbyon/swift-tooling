#!/usr/bin/env bash
set -euo pipefail

readonly test_root=$(cd -- "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)
readonly setup_script="$test_root/Scripts/setup-swift-tools.sh"
readonly runner="$test_root/bin/swift-tooling"
readonly release_builder="$test_root/Scripts/build-release.sh"
readonly mintfile_generator="$test_root/Scripts/generate-mintfile.sh"
readonly toolchain_lock_parser="$test_root/Scripts/toolchain-lock.sh"
readonly test_temp_root=$(mktemp -d "${TMPDIR:-/tmp}/swift-tooling-tests.XXXXXX")

cleanup() {
    rm -rf "$test_temp_root"
}

trap cleanup EXIT

failures=0

fail() {
    printf 'FAIL: %s\n' "$1" >&2
    failures=$((failures + 1))
}

assert_file_exists() {
    if [[ ! -f "$1" ]]; then
        fail "expected file to exist: $1"
    fi
}

assert_file_not_exists() {
    if [[ -e "$1" ]]; then
        fail "expected path not to exist: $1"
    fi
}

assert_contains() {
    local file=$1
    local expected=$2
    if ! grep -Fq -- "$expected" "$file"; then
        fail "expected '$expected' in $file"
    fi
}

assert_order() {
    local file=$1
    local first=$2
    local second=$3
    local first_line second_line
    first_line=$(grep -Fn -- "$first" "$file" | head -n 1 | cut -d: -f1 || true)
    second_line=$(grep -Fn -- "$second" "$file" | head -n 1 | cut -d: -f1 || true)
    if [[ -z "$first_line" || -z "$second_line" || "$first_line" -ge "$second_line" ]]; then
        fail "expected '$first' before '$second' in $file"
    fi
}

assert_equal() {
    if [[ "$1" != "$2" ]]; then
        fail "expected '$1' to equal '$2'"
    fi
}

new_fixture() {
    local fixture
    fixture=$(mktemp -d "$test_temp_root/fixture.XXXXXX")
    mkdir -p "$fixture/consumer/Scripts" "$fixture/consumer/Sources" "$fixture/consumer/Tests"
    printf '%s\n' '#!/usr/bin/env bash' 'exit 0' > "$fixture/consumer/Scripts/with-xcode.sh"
    printf '%s\n' 'source-root' > "$fixture/consumer/Sources/Example.swift"
    printf '%s\n' 'test-root' > "$fixture/consumer/Tests/ExampleTests.swift"
    printf '%s\n' '# local swiftformat options' > "$fixture/consumer/.swiftformat"
    printf '%s\n' '# local swiftlint options' > "$fixture/consumer/.swiftlint.yml"
    printf '%s\n' '# generated by the consumer' > "$fixture/consumer/.gitignore"
    printf '%s\n' "$fixture"
}

new_release_archive() {
    local fixture=$1
    local version=$2
    local release_root="$fixture/release"
    local archive="$fixture/swift-tooling-$version.tar.gz"

    mkdir -p "$release_root/bin" "$release_root/config" "$release_root/Scripts"
    printf '%s\n' '#!/usr/bin/env bash' 'exit 0' > "$release_root/bin/swift-tooling"
    printf '%s\n' '#!/usr/bin/env bash' 'exit 0' > "$release_root/Scripts/setup-swift-tools.sh"
    printf '%s\n' '#!/usr/bin/env bash' 'exit 0' > "$release_root/Scripts/swift-tools.sh"
    cp "$test_root/Scripts/toolchain-lock.sh" "$release_root/Scripts/toolchain-lock.sh"
    printf '%s\n' '# local configuration template' > "$release_root/Scripts/swift-tools-local.sh"
    printf '%s\n' 'base format' > "$release_root/config/swiftformat.base"
    printf '%s\n' 'base lint' > "$release_root/config/swiftlint.base.yml"
    printf '%s\n' 'MINT_VERSION=0.18.0' > "$release_root/toolchain.lock"
    printf '%s\n' 'nicklockwood/SwiftFormat@0.63.0' 'realm/SwiftLint@0.65.1' > "$release_root/Mintfile"
    chmod 0755 "$release_root/bin/swift-tooling" "$release_root/Scripts/setup-swift-tools.sh" \
        "$release_root/Scripts/swift-tools.sh"
    tar -czf "$archive" -C "$release_root" .
    shasum -a 256 "$archive" | awk '{print $1}'
}

new_unsafe_release_archive() {
    local fixture=$1
    local version=$2
    local archive="$fixture/swift-tooling-$version-unsafe.tar.gz"

    new_release_archive "$fixture" "$version" >/dev/null
    printf '%s\n' 'outside release root' > "$fixture/outside-release-root"
    ln -s "$fixture/outside-release-root" "$fixture/release/unsafe-link"
    tar -czf "$archive" -C "$fixture/release" .
    shasum -a 256 "$archive" | awk '{print $1}'
}

new_mint_archive() {
    local fixture=$1
    local archive_kind=${2:-valid}
    local mint_source="$fixture/mint-source"
    local mint_archive="$fixture/mint.zip"
    local mint_sha

    mkdir -p "$fixture/release/Scripts" "$mint_source"
    cp "$test_root/Scripts/toolchain-lock.sh" "$fixture/release/Scripts/toolchain-lock.sh"
    printf '%s\n' '#!/usr/bin/env bash' 'exit 0' > "$mint_source/mint"
    if [[ "$archive_kind" = unsafe ]]; then
        printf '%s\n' 'outside mint archive' > "$fixture/outside-mint-archive"
        ln -s "$fixture/outside-mint-archive" "$mint_source/unsafe-link"
        (cd "$mint_source" && zip -q -y "$mint_archive" mint unsafe-link)
    else
        (cd "$mint_source" && zip -q "$mint_archive" mint)
    fi
    mint_sha=$(shasum -a 256 "$mint_archive" | awk '{print $1}')
    printf '%s\n' \
        'MINT_VERSION=0.18.0' \
        "MINT_ARCHIVE_URL=file://$mint_archive" \
        "MINT_ARCHIVE_SHA256=$mint_sha" \
        'SWIFTFORMAT_PACKAGE=nicklockwood/SwiftFormat' \
        'SWIFTFORMAT_VERSION=0.63.0' \
        'SWIFTLINT_PACKAGE=realm/SwiftLint' \
        'SWIFTLINT_VERSION=0.65.1' > "$fixture/release/toolchain.lock"
    printf '%s\n' 'nicklockwood/SwiftFormat@0.63.0' 'realm/SwiftLint@0.65.1' > "$fixture/release/Mintfile"
    printf '%s\n' "$mint_sha"
}

test_setup_installs_and_is_idempotent() {
    local fixture archive_sha archive consumer
    fixture=$(new_fixture)
    consumer="$fixture/consumer"
    archive_sha=$(new_release_archive "$fixture" v1.0.0)
    archive="$fixture/swift-tooling-v1.0.0.tar.gz"

    if ! bash "$setup_script" \
        --repository-root "$consumer" \
        --release-archive "$archive" \
        --release-version v1.0.0 \
        --release-sha256 "$archive_sha"; then
        fail 'initial setup should succeed'
        return
    fi

    assert_file_exists "$consumer/.tools/swift-tooling/v1.0.0/bin/swift-tooling"
    assert_file_exists "$consumer/Scripts/swift-tools.sh"
    assert_file_exists "$consumer/Scripts/swift-tools.lock"
    assert_file_exists "$consumer/Scripts/swift-tools-local.sh"
    assert_contains "$consumer/.gitignore" '.tools/'
    assert_contains "$consumer/Scripts/swift-tools.lock" \
        'SWIFT_TOOLING_RELEASE_ASSET=swift-tooling-v1.0.0.tar.gz'

    local adapter_before lock_before local_before ignore_before
    adapter_before=$(shasum -a 256 "$consumer/Scripts/swift-tools.sh")
    lock_before=$(shasum -a 256 "$consumer/Scripts/swift-tools.lock")
    ignore_before=$(shasum -a 256 "$consumer/.gitignore")
    printf '%s\n' '# user customization' >> "$consumer/Scripts/swift-tools-local.sh"
    local_before=$(shasum -a 256 "$consumer/Scripts/swift-tools-local.sh")

    if ! bash "$setup_script" \
        --repository-root "$consumer" \
        --release-archive "$archive" \
        --release-version v1.0.0 \
        --release-sha256 "$archive_sha"; then
        fail 'repeated setup should succeed'
        return
    fi

    assert_equal "$adapter_before" "$(shasum -a 256 "$consumer/Scripts/swift-tools.sh")"
    assert_equal "$lock_before" "$(shasum -a 256 "$consumer/Scripts/swift-tools.lock")"
    assert_equal "$local_before" "$(shasum -a 256 "$consumer/Scripts/swift-tools-local.sh")"
    assert_equal "$ignore_before" "$(shasum -a 256 "$consumer/.gitignore")"
    assert_equal 1 "$(grep -Fc '.tools/' "$consumer/.gitignore")"
}

