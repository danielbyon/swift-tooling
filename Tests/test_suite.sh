    cat > "$lock" <<'LOCK'
export MINT_ARCHIVE_URL="https://example.com/mint.zip\"?channel=stable"
LOCK

    if ! parsed=$(bash -c 'source "$1"; toolchain_lock_value "$2" MINT_ARCHIVE_URL' \
        _ "$toolchain_lock_parser" "$lock"); then
        fail 'parsing an escaped quoted lock value should succeed'
        return
    fi
    assert_equal 'https://example.com/mint.zip"?channel=stable' "$parsed"
}

test_built_release_installs_and_runs_through_consumer_adapter() {
    local fixture output consumer archive archive_sha fake_mint log effective_count
    fixture=$(new_fixture)
    output="$fixture/dist"
    consumer="$fixture/consumer"

    if ! bash "$release_builder" v1.0.0 "$output" >/dev/null; then
        fail 'a built release should be installable'
        return
    fi

    archive="$output/swift-tooling-v1.0.0.tar.gz"
    archive_sha=$(shasum -a 256 "$archive" | awk '{print $1}')
    if ! bash "$setup_script" \
        --repository-root "$consumer" \
        --release-archive "$archive" \
        --release-version v1.0.0 \
        --release-sha256 "$archive_sha" \
        --release-asset "$(basename "$archive")" >/dev/null; then
        fail 'a built release should install successfully'
        return
    fi

    cat > "$consumer/Scripts/swift-tools-local.sh" <<'LOCAL_CONFIG'
SWIFT_TOOLS_SOURCE_PATHS=(Sources Tests)
SWIFT_TOOLS_SWIFTFORMAT_CONFIG=.swiftformat
SWIFT_TOOLS_SWIFTLINT_CONFIG=.swiftlint.yml
SWIFT_TOOLS_COMMAND_PREFIX=()
LOCAL_CONFIG

    fake_mint="$fixture/fake-mint"
    log="$fixture/mint.log"
    cat > "$fake_mint" <<'FAKE_MINT'
#!/usr/bin/env bash
set -euo pipefail
printf '%s\n' "$*" >> "${FAKE_MINT_LOG:?}"
FAKE_MINT
    chmod 0755 "$fake_mint"

    if ! FAKE_MINT_LOG="$log" SWIFT_TOOLING_MINT_BINARY="$fake_mint" \
        bash "$consumer/Scripts/swift-tools.sh" lint; then
        fail 'the installed release should run through the consumer adapter'
        return
    fi

    assert_contains "$log" 'nicklockwood/SwiftFormat@0.63.0'
    assert_contains "$log" 'realm/SwiftLint@0.65.1'
    effective_count=$(find "$consumer" -maxdepth 1 -name '.swiftformat.effective.*' -type f | wc -l | tr -d ' ')
    assert_equal 0 "$effective_count"

    printf '%s\n' 'corrupted release archive' > \
        "$consumer/.tools/swift-tooling/v1.0.0/.swift-tooling-release.tar.gz"
    if FAKE_MINT_LOG="$log" \
        SWIFT_TOOLING_RELEASE_ARCHIVE="$consumer/.tools/swift-tooling/v1.0.0/.swift-tooling-release.tar.gz" \
        SWIFT_TOOLING_MINT_BINARY="$fake_mint" \
        bash "$consumer/Scripts/swift-tools.sh" exec swiftlint lint; then
        fail 'the consumer adapter should reject a corrupted cached release'
    fi
}

