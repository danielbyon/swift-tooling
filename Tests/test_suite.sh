        'SWIFTFORMAT_VERSION=0.63.0' 'SWIFTLINT_PACKAGE=realm/SwiftLint' \
        'SWIFTLINT_VERSION=0.65.1' > "$fixture/release/toolchain.lock"
    fake_mint="$fixture/fake-mint"
